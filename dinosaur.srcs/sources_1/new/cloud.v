            cloud[17][95] <= cloud[17][0];
            cloud[18][95] <= cloud[18][0];
            cloud[19][95] <= cloud[19][0];
            cloud[20][95] <= cloud[20][0];
        end
    end
    
    always @(*) begin
        if(cloud[y][x]) begin
            en4 = 1;
            cloud_data = 16'b11111_111111_11111;
        end
        else en4 = 0;
    end
    
